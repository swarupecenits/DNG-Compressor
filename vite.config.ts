import { createHash } from "node:crypto";
import { readFileSync, readdirSync } from "node:fs";
import { join, relative, sep } from "node:path";
import type { Plugin } from "vite";
import { defineConfig } from "vitest/config";

const CONTENT_SECURITY_POLICY = [
  "default-src 'self'",
  "script-src 'self' 'wasm-unsafe-eval'",
  "worker-src 'self'",
  "connect-src 'self'",
  "img-src 'self' data: blob:",
  "style-src 'self'",
  "object-src 'none'",
  "base-uri 'self'",
  "form-action 'none'",
].join("; ");

function listFiles(dir: string): string[] {
  return readdirSync(dir, { withFileTypes: true }).flatMap((entry) => {
    const path = join(dir, entry.name);
    return entry.isDirectory() ? listFiles(path) : [path];
  });
}

function serviceWorkerSource(version: string, assets: readonly string[]): string {
  return `// Generated by vite.config.ts — offline support for DNG Squeeze.
const CACHE = "dng-squeeze-${version}";
const ASSETS = ${JSON.stringify(assets)};

// Bypass the HTTP cache so a new version never precaches stale files.
self.addEventListener("install", (event) => {
  event.waitUntil(
    caches.open(CACHE).then((cache) => cache.addAll(ASSETS.map((url) => new Request(url, { cache: "reload" })))),
  );
});

self.addEventListener("activate", (event) => {
  event.waitUntil(
    caches
      .keys()
      .then((keys) =>
        Promise.all(
          keys
            .filter((key) => key.startsWith("dng-squeeze-") && key !== CACHE)
            .map((key) => caches.delete(key)),
        ),
      )
      .then(() => self.clients.claim()),
  );
});

// The page asks for this when the user taps "Reload" on the update toast.
self.addEventListener("message", (event) => {
  if (event.data === "skip-waiting") self.skipWaiting();
});

// Cache first: every version is precached whole, so pages and files always match.
self.addEventListener("fetch", (event) => {
  const { request } = event;
  if (request.method !== "GET" || new URL(request.url).origin !== self.location.origin) return;
  event.respondWith(
    caches.open(CACHE).then(async (cache) => {
      const hit = await cache.match(request, { ignoreSearch: true });
      if (hit) return hit;
      try {
        return await fetch(request);
      } catch (error) {
        if (request.mode !== "navigate") throw error;
        return (await cache.match("./")) || Response.error();
      }
    }),
  );
});
`;
}

/** Emits sw.js precaching every build output and public file. */
function serviceWorker(): Plugin {
  let publicDir = "";
  return {
    name: "dng-squeeze:service-worker",
    apply: "build",
    enforce: "post",
    configResolved(config) {
      publicDir = config.publicDir;
    },
    generateBundle(_options, bundle) {
      const hash = createHash("sha256");
      const assets = new Set<string>(["./"]);
      for (const [fileName, output] of Object.entries(bundle)) {
        if (fileName.endsWith(".map")) continue;
        assets.add(`./${fileName}`);
        hash.update(fileName);
        if (output.type === "asset") hash.update(output.source);
      }
      for (const file of publicDir ? listFiles(publicDir) : []) {
        const name = relative(publicDir, file).split(sep).join("/");
        assets.add(`./${name}`);
        hash.update(name);
        hash.update(readFileSync(file));
      }
      const version = hash.digest("hex").slice(0, 12);
      this.emitFile({
        type: "asset",
        fileName: "sw.js",
        source: serviceWorkerSource(version, [...assets].sort()),
      });
    },
  };
}

/** Adds a strict Content-Security-Policy to the production HTML, right after the charset. */
function contentSecurityPolicy(): Plugin {
  const charset = /<meta charset="utf-8" \/>/i;
  return {
    name: "dng-squeeze:csp",
    apply: "build",
    transformIndexHtml(html) {
      if (!charset.test(html)) throw new Error("index.html needs <meta charset=\"utf-8\" /> for the CSP to follow");
      return html.replace(
        charset,
        (tag) => `${tag}\n    <meta http-equiv="Content-Security-Policy" content="${CONTENT_SECURITY_POLICY}" />`,
      );
    },
  };
}

